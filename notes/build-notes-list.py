#!/usr/bin/env python3
"""Write site/_companion-notes.md, the list of companion notes the course home page includes.

The order and titles come from notes-order.md, the same file the notes pages use
for their previous/next links, so the home page, the links and the pages agree.
Run after adding or reordering notes, before rendering the site:
    python3 build-notes-list.py
"""
import pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "lectures"))
import notes_common as nc

lines = ["<!-- generated by notes/build-notes-list.py from notes/notes-order.md; edit those, not this -->", ""]
for n, (path, title) in enumerate(nc.read_order(), 1):
    lines.append("%d. [%s](notes/%s)" % (n, title, path))
(HERE.parent / "site" / "_companion-notes.md").write_text("\n".join(lines) + "\n")
print("wrote site/_companion-notes.md with %d notes" % len(lines[2:]))
